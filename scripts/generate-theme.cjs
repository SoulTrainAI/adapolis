// Generates src/app/theme.css and src/lib/theme/colors.cjs from Tailwind's palette.
const colors = require('tailwindcss/colors');
const fs = require('fs');
const PALETTES = ['slate','violet','emerald','red','amber','sky','rose','blue','orange','yellow','green','fuchsia','cyan','pink','teal','indigo'];
const SHADES = [50,100,200,300,400,500,600,700,800,900,950];
const rgb = (hex) => { const h = hex.replace('#',''); return [0,2,4].map(i => parseInt(h.slice(i,i+2),16)).join(' '); };
// Light mode: neutrals invert fully; colours invert their pale/deep ends but keep 500-700 so buttons stay the same.
const NEUTRAL = {50:950,100:900,200:800,300:700,400:600,500:500,600:400,700:300,800:200,900:100,950:50};
const CHROMA  = {50:950,100:900,200:800,300:700,400:600,500:500,600:600,700:700,800:200,900:100,950:50};
const BRAND_DARK = { navy:'#0b1020', ink:'#141c38', violet:'#8b5cf6', lilac:'#c4b5fd', gold:'#f5b301', 'gold-light':'#fcd34d' };
const BRAND_LIGHT = { navy:'#f8fafc', ink:'#ffffff', violet:'#7c3aed', lilac:'#7c3aed', gold:'#d99a00', 'gold-light':'#b45309' };
const SOLID = ['html.light [class*="bg-brand-violet"]', 'html.light [class*="bg-brand-gold"]'];
for (const p of PALETTES.filter((x) => x !== 'slate')) for (const n of [5, 6, 7]) SOLID.push(`html.light [class*="bg-${p}-${n}"]`);
let dark = [], light = [];
for (const p of PALETTES) for (const s of SHADES) {
  dark.push(`  --c-${p}-${s}: ${rgb(colors[p][s])};`);
  light.push(`  --c-${p}-${s}: ${rgb(colors[p][(p==='slate'?NEUTRAL:CHROMA)[s]])};`);
}
dark.push('  --c-white: 255 255 255;'); light.push('  --c-white: 15 23 42;');
for (const [k,v] of Object.entries(BRAND_DARK)) dark.push(`  --c-brand-${k}: ${rgb(v)};`);
for (const [k,v] of Object.entries(BRAND_LIGHT)) light.push(`  --c-brand-${k}: ${rgb(v)};`);
const css = `/* Generated by scripts/generate-theme.cjs: run \`node scripts/generate-theme.cjs\` after changing palettes. */
/* Dark is the default. html.light swaps the palette; .theme-dark keeps a subtree dark (trading cards). */
:root,
html.light .theme-dark {
${dark.join('\n')}
  --background: #0b1020;
  --foreground: #e2e8f0;
}

html.light {
${light.join('\n')}
  --background: #f8fafc;
  --foreground: #0f172a;
  color-scheme: light;
}

/* Text on a solid colour button keeps its dark-mode colour in light mode. */
${SOLID.join(',\n')} {
  --c-white: 255 255 255;
  --c-brand-navy: 11 16 32;
}
`;
fs.writeFileSync('src/app/theme.css', css);
const tw = {};
for (const p of PALETTES) { tw[p] = {}; for (const s of SHADES) tw[p][s] = `rgb(var(--c-${p}-${s}) / <alpha-value>)`; }
tw.white = 'rgb(var(--c-white) / <alpha-value>)';
tw.brand = {}; for (const k of Object.keys(BRAND_DARK)) tw.brand[k] = `rgb(var(--c-brand-${k}) / <alpha-value>)`;
fs.mkdirSync('src/lib/theme', { recursive: true });
fs.writeFileSync('src/lib/theme/colors.cjs', '// Generated by scripts/generate-theme.cjs\nmodule.exports = ' + JSON.stringify(tw, null, 2) + ';\n');
console.log('ok');
